"""A paper trial that settles itself, so "is the edge real" stops being a guess.

`backtest.py` has always been ready to answer that question and has never had an input
file. The Kalshi half of that is now fixed (`settle.py`), but the only healthy flow this
project has is the whale board - and board tickets are Polymarket markets, which
`settle.py` does not and should not know about. This module is the missing half: it
takes each published ticket, holds it, and labels it when the market resolves.

WHY IT LIVES IN ``docs/``: the board is regenerated by a GitHub Action on a fresh
checkout every ~15 minutes, and `.gitignore` excludes `data/` and `*.jsonl`, so a trial
kept there would be erased on every run. Writing to `docs/trial.json` - which the
workflow already commits - means the trial accrues automatically from a job that
already exists, and every position lands in the public commit log at the moment it was
opened. That last part is the real prize: the standard objection to a paper record is
that it could have been written after the fact, and a git history on a public repo is
the cheapest possible answer to it.

DELIBERATELY FLAT STAKES. Tickets are recorded at a fixed notional rather than at the
board's conviction-weighted size, because those are two different hypotheses - "the
signal picks winners" and "the conviction score sizes them well" - and you cannot test
two hypotheses with zero data. Test the signal first; conviction is recorded on every
row so it can be sliced later, once there is something to slice.

``pred`` IS THE ENTRY PRICE, not a forecast of our own. The board is a copy-trade
signal: it claims a position is worth taking, never that P(win) is some number. So the
honest null is the market's own price, which makes `backtest`'s ``calibration_gap``
(avg_pred - win_rate) read directly as realised edge in probability points, with a
NEGATIVE gap meaning the tickets beat the price they were bought at.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

from .fees import trade_fee

# A resolved Polymarket market pays its winning leg at 1 and the rest at 0. Demanding
# the extremes - rather than trusting `closed` alone - is what keeps a UMA dispute or a
# mid-resolution read from being labelled as a settled bet. Anything in between stays
# open and is retried next run; an unsettleable position must never become a data point.
WON_AT = 0.99
LOST_AT = 0.01

DEFAULT_STAKE = 100.0


def _key(market_id: str, outcome: str) -> str:
    """One position per market leg, ever. First sighting wins.

    The board republishes the same ticket every cycle for as long as it qualifies, so
    without this the trial would record the same opinion dozens of times, inflate `n`
    with copies of one bet, and let a later, better price silently replace the one we
    would actually have paid.
    """
    return f"{market_id}:{outcome.strip().lower()}"


def load(path: str | Path) -> dict:
    p = Path(path)
    if not p.exists():
        return {"open": [], "settled": [], "stats": {}}
    data = json.loads(p.read_text(encoding="utf-8"))
    data.setdefault("open", [])
    data.setdefault("settled", [])
    data.setdefault("stats", {})
    return data


def save(path: str | Path, trial: dict) -> None:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(trial, indent=2), encoding="utf-8")


def record(trial: dict, tickets: list[dict], *, stake: float = DEFAULT_STAKE,
           fee_multiplier: float = 0.07, maker: bool = True,
           now: float | None = None) -> int:
    """Open a paper position for each ticket not already held. Returns how many."""
    now = time.time() if now is None else now
    seen = {r["key"] for r in trial["open"]} | {r["key"] for r in trial["settled"]}
    added = 0
    for t in tickets:
        price = float(t.get("entry_price") or 0.0)
        if not 0.0 < price < 1.0:
            continue                       # unpriceable: not a position, not a data point
        key = _key(t.get("market_id", ""), t.get("outcome", ""))
        if key in seen:
            continue
        contracts = stake / price
        trial["open"].append({
            "key": key,
            "opened_at": now,
            "market_id": t.get("market_id", ""),
            "outcome": t.get("outcome", ""),
            "title": t.get("title", ""),
            "url": t.get("url", ""),
            "price": round(price, 4),
            "stake": round(stake, 4),
            "contracts": round(contracts, 4),
            # Everything below is for slicing the result later, not for scoring it.
            "conviction": t.get("conviction"),
            "n_wallets": t.get("n_wallets"),
            "whale_usd": t.get("whale_usd"),
            "drift_c": t.get("drift_c"),
            "hours_to_resolve": t.get("hours_to_resolve"),
            "liquidity": t.get("liquidity"),
            "end_iso": t.get("end_iso", ""),
            "event_iso": t.get("event_iso", ""),
            "fee": trade_fee(price, max(1, round(contracts)),
                             multiplier=fee_multiplier, maker=maker),
        })
        seen.add(key)
        added += 1
    return added


def _winner(meta: dict) -> str | None:
    """Name of the winning outcome, or None if this market has not cleanly resolved."""
    if not meta.get("closed"):
        return None
    names = meta.get("outcomes") or []
    prices = meta.get("prices") or []
    if len(names) != len(prices) or not names:
        return None
    winners = [n for n, p in zip(names, prices) if p >= WON_AT]
    losers = [n for n, p in zip(names, prices) if p <= LOST_AT]
    # Exactly one leg at 1 and every other at 0. A market that is closed but still
    # quoting anything in between is mid-resolution or disputed, and saying so is the
    # whole point - a paper record that guesses is worth less than no paper record.
    if len(winners) == 1 and len(losers) == len(names) - 1:
        return winners[0]
    return None


def settle(trial: dict, metas: dict[str, dict], *, now: float | None = None) -> int:
    """Label every open position whose market has resolved. Returns how many."""
    now = time.time() if now is None else now
    still_open, settled = [], 0
    for row in trial["open"]:
        winner = _winner(metas.get(row["market_id"]) or {})
        if winner is None:
            still_open.append(row)
            continue
        won = winner.strip().lower() == row["outcome"].strip().lower()
        price, contracts, stake, fee = (
            row["price"], row["contracts"], row["stake"], row["fee"])
        realized = (contracts * (1.0 - price) - fee) if won else (-stake - fee)
        trial["settled"].append({
            **row,
            "settled_at": now,
            "winner": winner,
            "won": won,
            # The market's own price at entry. See the module docstring: this makes
            # `calibration_gap` read as realised edge, with negative meaning we beat it.
            "pred": price,
            "realized": round(realized, 4),
        })
        settled += 1
    trial["open"] = still_open
    return settled


def stats(trial: dict, *, min_n: int = 30) -> dict:
    """Score the settled rows with the project's existing gate, plus trial bookkeeping."""
    from .backtest import evaluate

    out = evaluate(trial["settled"], min_n=min_n)
    out["open_positions"] = len(trial["open"])
    if trial["settled"]:
        span = max(r["settled_at"] for r in trial["settled"]) - \
            min(r["opened_at"] for r in trial["settled"])
        out["trial_days"] = round(span / 86400.0, 1)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="predictionedge.papertrial")
    ap.add_argument("--board", default="docs/board.json")
    ap.add_argument("--trial", default="docs/trial.json")
    ap.add_argument("--stake", type=float, default=DEFAULT_STAKE)
    ap.add_argument("--no-settle", action="store_true",
                    help="record new tickets but skip the settlement fetch")
    args = ap.parse_args(argv)

    from .config import Config
    cfg = Config.from_env()
    trial = load(args.trial)

    board = json.loads(Path(args.board).read_text(encoding="utf-8"))
    # Stamp positions with when the board SAW that price, not when this process ran.
    # They differ whenever a scheduled run is skipped or the board is replayed, and the
    # hold time is what the whole trial measures - dating an entry to the replay would
    # quietly shorten every holding period in the record.
    added = record(trial, board.get("tickets") or [], stake=args.stake,
                   fee_multiplier=cfg.fee_multiplier, maker=cfg.assume_maker,
                   now=board.get("generated_at") or None)

    settled = 0
    if not args.no_settle and trial["open"]:
        from .gamma import market_meta
        # Only open positions need a lookup, and they are the markets that have
        # dropped OFF the board - a resolved market is exactly the one the board
        # stopped showing, so this cannot be answered from board.json.
        metas = market_meta([r["market_id"] for r in trial["open"]])
        settled = settle(trial, metas)

    trial["stats"] = stats(trial)
    trial["generated"] = time.strftime("%Y-%m-%d %H:%M:%S")
    save(args.trial, trial)

    s = trial["stats"]
    print(f"recorded {added} new, settled {settled}; "
          f"{s.get('open_positions', 0)} open, {s.get('n', 0)} settled")
    if s.get("n"):
        print(f"  win rate {s['win_rate']:.1%} vs avg entry price "
              f"{s['avg_predicted']:.1%}  (edge {-s['calibration_gap']:+.1%} pts)")
        print(f"  ROI on stake {s['roi_on_stake']:+.2%}  "
              f"mean return {s['mean_return']:+.4f}  deploy={s['deploy']}")
        if s.get("reasons"):
            print("  not deployable: " + "; ".join(s["reasons"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
